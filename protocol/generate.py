"""Generate the shared numeric contract. Run from any directory."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def outputs():
    s=json.loads((ROOT/'protocol/schema.json').read_text())
    values={'MAJOR':s['wire'][0],'MINOR':s['wire'][1]}
    for group,prefix in [('types','TYPE'),('opcodes','OP'),('frames','CAN')]:
        values.update({f'{prefix}_{k.upper()}':v for k,v in s[group].items()})
    values.update({f'OBJ_{k.upper()}':v['id'] for k,v in s['objects'].items()})
    for prefix,items in s['enums'].items():values.update({f'{prefix}_{k}':v for k,v in items.items()})
    values.update({f'FIELD_{name.upper()}':int(number) for number,name in s['sample_fields'].items()})
    py='# Generated by protocol/generate.py; edit schema.json.\n'+''.join(f'{k} = {v}\n' for k,v in values.items())
    py+='SAMPLE_FIELDS = '+repr({int(k):v for k,v in s['sample_fields'].items()})+'\n'
    py+='OBJECTS = '+repr({v['id']:(k,s['types'][v['type']]) for k,v in s['objects'].items()})+'\n'
    py+='COMPOUNDS = '+repr({k:{int(n):(v[0],s['types'][v[1]]) for n,v in rows.items()} for k,rows in s['compounds'].items()})+'\n'
    h='#ifndef MB_PROTOCOL_H\n#define MB_PROTOCOL_H\n/* Generated from protocol/schema.json. */\n'+''.join(f'#define MB_{k} {v}u\n' for k,v in values.items())+'#define MB_SDK_VERSION "'+s['sdk']+'"\n#endif\n'
    md='# MBP/1 object dictionary\n\nGenerated from `schema.json`; integers are little endian.\n\n| ID | Name | Type |\n|---|---|---|\n'+''.join(f'| 0x{v["id"]:04X} | {k} | {v["type"]} |\n' for k,v in s['objects'].items())
    dbc='VERSION "MBP/1.0"\nNS_ :\nBS_:\nBU_: Host Drive\n'
    for name,base in s['frames'].items():
        dbc+=f'BO_ {base+1} {name.upper()}_NODE1: 8 '+('Host' if name in ('stop','control_heartbeat','request','diagnostic_request') else 'Drive')+'\n'
        receiver='Drive' if name in ('stop','control_heartbeat','request','diagnostic_request') else 'Host'
        for field,start,bits in s['frame_layouts'].get(name,[['isotp_payload',0,64]]):
            dbc+=f' SG_ {field} : {start}|{bits}@1+ (1,0) [0|{(1<<bits)-1}] "raw" {receiver}\n'
    return {'protocol/generated.py':py,'motor_sdk/include/mb_protocol.h':h,'protocol/objects.md':md,'protocol/mbp.dbc':dbc}
if __name__=='__main__':
    for name,data in outputs().items(): (ROOT/name).write_text(data)
